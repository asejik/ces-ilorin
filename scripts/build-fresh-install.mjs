#!/usr/bin/env node
/**
 * Builds ONE SQL file that sets up a brand-new, dedicated CES Supabase project from the
 * migrations, in order. Paste the output into the new project's SQL editor and run it once.
 *
 *   node scripts/build-fresh-install.mjs   ->  supabase/fresh-install/ces_fresh_install.sql
 *
 * What it leaves out on purpose:
 *  - *_rollback.sql files
 *  - 20260919_seed_admin_staff.sql (needs your real admin email: use scripts/make-staff.mjs)
 *  - schema-wide / "anon" blanket GRANT and ALTER DEFAULT PRIVILEGES lines written for the old
 *    shared project. The lockdown migration then grants only service_role (the server) on the
 *    CES tables, so a dedicated project starts with the safe permissions from day one.
 */
import fs from 'node:fs';
import path from 'node:path';

const dir = 'supabase/migrations';
const skip = (f) => f.endsWith('_rollback.sql') || f.includes('rollback_init') || f === '20260919_seed_admin_staff.sql';
const files = fs.readdirSync(dir).filter((f) => f.endsWith('.sql') && !skip(f)).sort();

// Statement-level removal of the blanket grants (they can span one line each).
const blanket = (line) => {
  const t = line.trim().toUpperCase();
  if (t.startsWith('ALTER DEFAULT PRIVILEGES')) return true;
  if (t.startsWith('GRANT') && /\bANON\b/.test(t)) return true;
  return false;
};

let out = `-- ==============================================================================
-- CES FRESH INSTALL (generated by scripts/build-fresh-install.mjs - do not edit by hand)
-- For a NEW, dedicated Supabase project only. Run once in the SQL editor.
-- Migrations included, in order:
${files.map((f) => `--   ${f}`).join('\n')}
-- ==============================================================================
`;

for (const f of files) {
  const lines = fs.readFileSync(path.join(dir, f), 'utf8').replace(/\r\n/g, '\n').split('\n');
  const kept = [];
  let removed = 0;
  for (const line of lines) {
    if (blanket(line)) {
      removed++;
      kept.push(`-- [fresh-install: removed blanket grant] ${line.trim()}`);
    } else kept.push(line);
  }
  out += `\n\n-- ---------------------------------------------------------------\n-- BEGIN FILE: ${f}${removed ? `  (${removed} blanket grant line(s) removed)` : ''}\n-- ---------------------------------------------------------------\n${kept.join('\n')}\n`;
}

fs.mkdirSync('supabase/fresh-install', { recursive: true });
fs.writeFileSync('supabase/fresh-install/ces_fresh_install.sql', out);
console.log(`Wrote supabase/fresh-install/ces_fresh_install.sql from ${files.length} migrations (${out.length} chars).`);
